#!/usr/bin/env node
/**
 * Generates content/core/*.xml: the "system" elements every character needs
 * (levels, base statistics, internal grants, sizes, conditions...). These are
 * referenced by ids from community content, so ids must stay stable.
 *
 * Run: node scripts/generate-core.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "content", "core");
mkdirSync(outDir, { recursive: true });

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const attrs = (o) =>
  Object.entries(o)
    .filter(([, v]) => v !== undefined && v !== null && v !== "")
    .map(([k, v]) => ` ${k}="${esc(v)}"`)
    .join("");

function element({ name, type, id, source = "Core", supports, requirements, description, setters, rules, sheet, body }) {
  const lines = [`\t<element${attrs({ name, type, source, id })}>`];
  if (supports) lines.push(`\t\t<supports>${esc(supports)}</supports>`);
  if (requirements) lines.push(`\t\t<requirements>${esc(requirements)}</requirements>`);
  if (description) lines.push(`\t\t<description>${description}</description>`);
  if (sheet === false) lines.push(`\t\t<sheet display="false" />`);
  if (setters && setters.length) {
    lines.push(`\t\t<setters>`);
    for (const [n, v] of setters) lines.push(`\t\t\t<set name="${esc(n)}">${esc(v)}</set>`);
    lines.push(`\t\t</setters>`);
  }
  if (body) lines.push(body);
  if (rules && rules.length) {
    lines.push(`\t\t<rules>`);
    for (const r of rules) lines.push(`\t\t\t${r}`);
    lines.push(`\t\t</rules>`);
  }
  lines.push(`\t</element>`);
  return lines.join("\n");
}

const stat = (o) => `<stat${attrs(o)} />`;
const grant = (o) => `<grant${attrs(o)} />`;
const select = (o) => `<select${attrs(o)} />`;

function file(name, title, description, elements) {
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-core.mjs; edit the generator, not this file. -->
<elements>
\t<info>
\t\t<name>${esc(title)}</name>
\t\t<description>${esc(description)}</description>
\t\t<author url="https://github.com/SpikeTheDragon40k/dndbuilderclaude">dndbuilder contributors</author>
\t</info>

${elements.join("\n\n")}
</elements>
`;
  writeFileSync(join(outDir, name), xml);
  console.log(`wrote content/core/${name} (${elements.length} elements)`);
}

